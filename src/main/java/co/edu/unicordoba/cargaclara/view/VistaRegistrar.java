    private final GestorEncomiendas gestor;
    private final Consumer<String> onEncomiendaRegistrada;
    
    private final JTextField txtCodigo = new JTextField();
    private final JTextField txtRemitente = new JTextField();
    private final JTextField txtDestinatario = new JTextField();
    private final JTextField txtOrigen = new JTextField();
    private final JTextField txtDestino = new JTextField();
    private final JTextField txtPeso = new JTextField();
    private final JComboBox<String> cmbModalidad =
            new JComboBox<>(new String[]{"Estándar", "Express"});
    private final JLabel lblResultadoFlete = new JLabel("Flete liquidado: $0");   
    
    public VistaRegistrar(GestorEncomiendas gestor, Consumer<String> onEncomiendaRegistrada) {
        this.gestor = gestor;
        this.onEncomiendaRegistrada = onEncomiendaRegistrada;
        setLayout(new GridLayout(8, 2, 8, 8));
        setBorder(BorderFactory.createTitledBorder("1. Registro y Liquidación de Flete"));

        add(new JLabel("Código de guía:"));
        add(txtCodigo);

        add(new JLabel("Remitente:"));
        add(txtRemitente);

        add(new JLabel("Destinatario:"));
        add(txtDestinatario);

        add(new JLabel("Origen:"));
        add(txtOrigen);

        add(new JLabel("Destino:"));
        add(txtDestino);

        add(new JLabel("Peso (kg):"));
        add(txtPeso);

        add(new JLabel("Modalidad:"));
        add(cmbModalidad);

        JButton btnRegistrar = new JButton("Registrar y Liquidar");
        btnRegistrar.addActionListener(e -> registrarEncomienda());
        add(btnRegistrar);
        add(lblResultadoFlete);        
        
    }
    
    private void registrarEncomienda() {
        try {
            String codigo = txtCodigo.getText().trim();
            String remitente = txtRemitente.getText().trim();
            String destinatario = txtDestinatario.getText().trim();
            String origen = txtOrigen.getText().trim();
            String destino = txtDestino.getText().trim();
            double peso = Double.parseDouble(txtPeso.getText().trim());

            LiquidacionFleteTemplate modalidad = "Express".equals(cmbModalidad.getSelectedItem())
                    ? new LiquidacionExpress()
                    : new LiquidacionEstandar();

            Encomienda encomienda = new Encomienda(codigo, remitente, destinatario, origen, destino, peso);
            gestor.registrarYLiquidar(encomienda, modalidad);

            lblResultadoFlete.setText(String.format(
                    "Flete liquidado (%s): $%.0f",
                    modalidad.getNombreModalidad(),
                    encomienda.getValorFlete()
            ));

            if (onEncomiendaRegistrada != null) {
                onEncomiendaRegistrada.accept(codigo);
            }

            limpiarCampos();
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(
                    this,
                    "Ingresa un peso numérico válido (ej. 4.5).",
                    "Error de formato",
                    JOptionPane.ERROR_MESSAGE
            );
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Error al registrar",
                    JOptionPane.WARNING_MESSAGE
            );
        }
    }
    
    private void limpiarCampos() {
        txtCodigo.setText("");
        txtRemitente.setText("");
        txtDestinatario.setText("");
        txtOrigen.setText("");
        txtDestino.setText("");
        txtPeso.setText("");
        txtCodigo.requestFocus();
    }

