    private final GestorEncomiendas gestor;
    private final JComboBox<String> cmbCodigos = new JComboBox<>();
    private final JComboBox<EstadoEncomienda> cmbEstados =
            new JComboBox<>(EstadoEncomienda.values());
    private final JTextArea areaBitacora = new JTextArea(8, 40);

    public VistaSeguimiento(GestorEncomiendas gestor) {
        this.gestor = gestor;

        setLayout(new BorderLayout(8, 8));
        setBorder(BorderFactory.createTitledBorder("2. Seguimiento de Estados (Observer)"));

        JPanel panelControles = new JPanel(new FlowLayout(FlowLayout.LEFT));
        panelControles.add(new JLabel("Guía:"));
        panelControles.add(cmbCodigos);
        panelControles.add(new JLabel("Nuevo estado:"));
        panelControles.add(cmbEstados);

        JButton btnActualizar = new JButton("Actualizar Estado");
        btnActualizar.addActionListener(e -> actualizarEstado());
        panelControles.add(btnActualizar);

        areaBitacora.setEditable(false);

        add(panelControles, BorderLayout.NORTH);
        add(new JScrollPane(areaBitacora), BorderLayout.CENTER);        
    }
    
    public void agregarCodigoGuia(String codigo) {
        for (int i = 0; i < cmbCodigos.getItemCount(); i++) {
            if (cmbCodigos.getItemAt(i).equalsIgnoreCase(codigo)) {
                cmbCodigos.setSelectedIndex(i);
                return;
            }
        }
        cmbCodigos.addItem(codigo);
        cmbCodigos.setSelectedItem(codigo);
    }
    
    private void actualizarEstado() {
        String codigo = (String) cmbCodigos.getSelectedItem();
        EstadoEncomienda nuevoEstado = (EstadoEncomienda) cmbEstados.getSelectedItem();

        if (codigo == null || codigo.isBlank() || nuevoEstado == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "Selecciona una guía registrada y un estado.",
                    "Aviso",
                    JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }

        try {
            gestor.cambiarEstado(codigo, nuevoEstado);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Error al cambiar estado",
                    JOptionPane.WARNING_MESSAGE
            );
        }
    }
    
    @Override
    public void onCambioEstado(
            Encomienda encomienda,
            EstadoEncomienda estadoAnterior,
            EstadoEncomienda estadoNuevo
    ) {
        areaBitacora.append(String.format(
                "[%s] %s -> %s | Destino: %s | Flete: $%.0f%n",
                encomienda.getCodigo(),
                estadoAnterior,
                estadoNuevo,
                encomienda.getDestino(),
                encomienda.getValorFlete()
        ));
    }

