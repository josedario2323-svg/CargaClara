    public GestorView(GestorEncomiendas gestor) {
        
        super("CargaClara - Liquidación y Seguimiento de Encomiendas");
        this.gestor = gestor;
        
        initComponents();
        
        panelCont.setLayout(new java.awt.BorderLayout());
        if (panelCont.getPreferredSize().width == 0 || panelCont.getPreferredSize().height == 0) {
        panelCont.setPreferredSize(new java.awt.Dimension(700, 420));
        }
        
        vs = new VistaSeguimiento(gestor);
        vr = new VistaRegistrar(gestor, vs::agregarCodigoGuia);        
        
        gestor.agregarObservadorPorDefecto(vs);
        gestor.agregarObservadorPorDefecto(new AlertaClienteObserver());
        gestor.agregarObservadorPorDefecto(
                new HistorialArchivoObserver("datos/historial_encomiendas.csv")
        );
        
        
        panelCont.removeAll();
        panelCont.add(vr, BorderLayout.CENTER);
        panelCont.revalidate();
        panelCont.repaint();
        
    }

